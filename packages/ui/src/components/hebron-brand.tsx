/** Como a marca se comporta sobre o fundo em que é aplicada. */
export type BrandTone =
  /** Paleta completa da marca. Padrão; exige fundo claro e neutro. */
  | "color"
  /** Monocromático branco, para superfícies escuras ou de marca. */
  | "light"
  /** Monocromático azul Hebron, para impressão e superfícies de baixo contraste. */
  | "dark";

interface Palette {
  blue: string;
  orange: string;
  green: string;
  cyan: string;
}

function palette(tone: BrandTone): Palette {
  if (tone === "light") {
    const white = "var(--hb-white)";
    return { blue: white, orange: white, green: white, cyan: white };
  }
  if (tone === "dark") {
    const blue = "var(--hb-blue)";
    return { blue, orange: blue, green: blue, cyan: blue };
  }
  return {
    blue: "var(--hb-blue)",
    orange: "var(--hb-orange)",
    green: "var(--hb-green)",
    cyan: "var(--hb-cyan)",
  };
}

