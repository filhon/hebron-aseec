const TODAY = new Date("2026-07-15T00:00:00Z");
const MS_PER_DAY = 24 * 60 * 60 * 1000;

const d = (offsetDays: number): Date =>
  new Date(TODAY.getTime() + offsetDays * MS_PER_DAY);

const past = (daysAgo: number): Date => d(-daysAgo);
const future = (daysAhead: number): Date => d(daysAhead);

const yearsAgo = (years: number): Date =>
  new Date(
    Date.UTC(
      TODAY.getUTCFullYear() - years,
      TODAY.getUTCMonth(),
      TODAY.getUTCDate(),
    ),
  );

